const hasUpstream=Boolean(process.env.MEMOS_NATIVE_ENTRY);
test('rc.5 private Settings adapter preserves credentials, other namespaces and comments',{skip:!hasUpstream},async(t)=>{
  const require=createRequire(process.env.MEMOS_NATIVE_ENTRY),{parseDocument}=require('yaml');
  const {Config}=await import('../vendor/memos-cloud-0.1.2.js');
  const home=await mkdtemp(join(tmpdir(),'memos-rc5-'));t.after(()=>rm(home,{recursive:true,force:true}));
  const file=join(home,'settings-legacy.yaml');
  const text='# existing configuration\nother-plugin:\n  untouched: true\nmemos-cloud:\n  apiKey: synthetic-unchanged-key\n  userId: synthetic-owner\n  apiKeyEnv: EXISTING_REF\n  baseURL: https://example.test/api\n  memoryLimitNumber: 8\n';
  await writeFile(file,text);
  const native={documentPath:join(home,'profiles','desktop','cordis.patch.yml'),writable:true};
  const settings=createLegacySettings({native,schema:Config,home,parseDocument});
  assert.equal(native.register,undefined);
  const controller=createController({settings});
  const initial=await controller.state();
  assert(initial.active);assert(initial.hasApiKey);assert.equal(initial.values.memoryLimitNumber,8);
  assert(!JSON.stringify(initial).includes('synthetic-unchanged-key'));
  assert.equal(await readFile(file,'utf8'),text);
  await controller.save({revision:initial.revision,values:{memoryLimitNumber:9},apiKey:''});
  const saved=await readFile(file,'utf8'),document=parseDocument(saved);
  assert(saved.startsWith('# existing configuration\n'));
  assert.equal(document.getIn(['other-plugin','untouched']),true);
  for(const key of ['apiKey','userId','apiKeyEnv','baseURL'])assert.equal(document.getIn(['memos-cloud',key]),parseDocument(text).getIn(['memos-cloud',key]));
  assert.equal(settings.get('memos-cloud').memoryLimitNumber,9);
  await assert.rejects(controller.save({revision:initial.revision,values:{memoryLimitNumber:10}}),/其他窗口/);
  const revision=(await controller.state()).revision;
  await controller.save({revision,resetFields:['memoryLimitNumber']});
  assert.equal(settings.get('memos-cloud').memoryLimitNumber,6);
  const beforeExternal=(await controller.state()).revision;
  await writeFile(file,(await readFile(file,'utf8')).replace('synthetic-owner','externally-changed-owner'));
  await assert.rejects(settings.mutate('memos-cloud',[{op:'set',path:['memoryLimitNumber'],value:11}],beforeExternal),{code:'SETTINGS_CONFLICT'});
  assert.equal(settings.get('memos-cloud').userId,'externally-changed-owner');
});

test('rc.5 private Settings adapter rejects malformed files and serializes conflicting saves',{skip:!hasUpstream},async(t)=>{
  const require=createRequire(process.env.MEMOS_NATIVE_ENTRY),{parseDocument}=require('yaml');
  const {Config}=await import('../vendor/memos-cloud-0.1.2.js');
  const home=await mkdtemp(join(tmpdir(),'memos-rc5-'));t.after(()=>rm(home,{recursive:true,force:true}));
  const file=join(home,'settings-legacy.yaml');
  await writeFile(file,'memos-cloud:\n  recallEnabled: false\n');
  const settings=createLegacySettings({native:{documentPath:join(home,'profile.yml')},schema:Config,home,parseDocument});
  const revision=settings.describe()[0].revision;
  const results=await Promise.allSettled([settings.mutate('memos-cloud',[{op:'set',path:['memoryLimitNumber'],value:7}],revision),settings.mutate('memos-cloud',[{op:'set',path:['memoryLimitNumber'],value:8}],revision)]);
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
  assert.equal(results.find(r=>r.status==='rejected').reason.code,'SETTINGS_CONFLICT');
  await writeFile(file,'memos-cloud: [invalid');
  assert.throws(()=>settings.get('memos-cloud'),/invalid/);
  assert.throws(()=>settings.describe(),/invalid/);
});

test('guarded entry applies on an unmodified rc.5 host API and uses the unchanged legacy account',{skip:!hasUpstream},async(t)=>{
  const {apply,Config}=await import('../lib/guarded-memos.js');
  const home=await mkdtemp(join(tmpdir(),'memos-rc5-lifecycle-'));t.after(()=>rm(home,{recursive:true,force:true}));
  const requests=[];
  const server=http.createServer(async(req,res)=>{let body='';for await(const chunk of req)body+=chunk;requests.push({body:JSON.parse(body),authorization:req.headers.authorization});res.writeHead(200,{'content-type':'application/json'}).end(JSON.stringify({code:0,data:{memory_detail_list:[]}}));});
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));t.after(()=>{server.closeAllConnections();return new Promise(resolve=>server.close(resolve));});
  const file=join(home,'settings-legacy.yaml');
  const text=JSON.stringify({'memos-cloud':{apiKey:'synthetic-legacy-key',userId:'legacy-owner-retained',baseURL:`http://127.0.0.1:${server.address().port}`,addEnabled:false}})+'\n';
  await writeFile(file,text);
  const events=new Map(),cleanup=[];
  const native={documentPath:join(home,'profiles','desktop','cordis.patch.yml'),writable:true};
  const ctx={settings:native,fiber:{},logger:()=>({warn:()=>{}}),get:name=>name==='profileContext'?{home}:name==='configEditor'?{entries:()=>[{options:{id:'memos-cloud',config:{}}}]}:name==='launchEnvironment'?{get:()=>undefined}:undefined,on:(name,fn)=>{events.set(name,fn);return()=>events.delete(name);},effect:fn=>{const dispose=fn();if(typeof dispose==='function')cleanup.push(dispose);return dispose;},inject:(_names,fn)=>fn(ctx)};
  t.after(async()=>{for(const fn of cleanup.reverse())await fn();});
  apply(ctx,Config({}));
  assert.equal(native.register,undefined);
  assert(privacyFor(ctx).guard.active);
  const session={id:'synthetic-rc5-session',header:{}};
  const decision={kind:'enter',messages:[{source:{kind:'user'},content:[{type:'text',text:'联系 demo@example.test'}]}]};
  await events.get('agent/pre-step')({agent:{session},step:1,signal:new AbortController().signal},async()=>decision);
  assert.equal(requests.length,1);
  assert.equal(requests[0].authorization,'Token synthetic-legacy-key');
  assert.equal(requests[0].body.user_id,'legacy-owner-retained');
  assert(!JSON.stringify(requests[0].body).includes('demo@example.test'));
  assert.equal(await readFile(file,'utf8'),text);
});
